# Asynchronous operation management for the Ingress-CPU-Disk queueing network.
"""
Operation manager for non-blocking inter-LP communication.

An *operation* is one asynchronous "send a request to another LP and wait for the
admission ACK" interaction. It is NOT a business request:

    * Request  : end-to-end business entity (request_id is kept for its whole life).
    * Visit    : one arrival of a request at a station (fresh visit_id each time).
    * Operation: one control exchange (ARRIVAL -> ADMISSION_ACK), fresh operation_id.

Design rules implemented here (see Phase 1 report, section 1.4):

    * An operation finishes exactly once, in one of: SUCCEEDED, TIMED_OUT,
      CANCELLED, FAILED. The Future bound to it is resolved exactly once.
    * Both accepted=True and accepted=False ACKs are a *successful* communication
      (SUCCEEDED). A rejected arrival is a business DROP decided at admission by the
      destination station; it is never a communication error.
    * An operation waits for the admission ACK only, never for SERVICE_COMPLETE.
    * Timeout / cancellation only end the *waiting*. They never cancel the request,
      never release a server, never cancel scheduled ARRIVAL / SERVICE_COMPLETE
      events and never trigger a retry.
    * Timeouts use simulation time (an OP_TIMEOUT event scheduled at t + delta),
      never wall-clock time. In the baseline performance configuration the deadline
      is disabled and no OP_TIMEOUT event is ever created.
    * Duplicate / late ACKs are recognised by operation_id, counted, and ignored.
    * A communication failure (unknown destination LP, malformed payload, unknown
      operation_id, ACK pairing mismatch) moves the operation to FAILED, cleans every
      pending operation, stores a diagnostic reason and raises OperationFailedError
      so that the event loop stops the replication in a controlled way (status
      FAILED). It is never counted as a DROPPED request.
    * Same-timestamp ties between ACK / timeout / cancel are resolved purely by the
      scheduling order of the event queue (FIFO on (timestamp, schedule sequence));
      the first valid terminating event wins, the later one is ignored.

Determinism: operation ids are "op-1", "op-2", ... generated by a per-manager
counter, so a new manager per replication gives reproducible ids.
"""

from __future__ import annotations

import asyncio
import math
from dataclasses import dataclass
from enum import Enum, IntEnum
from typing import Any, Callable, NoReturn, Optional

from bkitevsim.core.event import Event
from contracts import (
    EVENT_ADMISSION_ACK,
    EVENT_OP_TIMEOUT,
    OperationPayload,
    Request,
    Visit,
)


# -------------------------------------------------------------------------
# Exceptions
# -------------------------------------------------------------------------
class OperationError(Exception):
    """Base class of all operation-level errors."""


class OperationTimeoutError(OperationError):
    """Delivered to waiters when the ACK deadline (simulation time) expires."""


class OperationCancelledError(OperationError):
    """Delivered to waiters when the operation is cancelled."""


class OperationFailedError(OperationError):
    """
    Communication failure.

    Delivered to waiters of every pending operation, and also raised to the caller
    so that the event loop aborts the replication (status FAILED, failure_reason).
    """


# -------------------------------------------------------------------------
# State and records
# -------------------------------------------------------------------------
class OperationState(IntEnum):
    """Operation lifecycle. The integer value is stored compactly per operation."""
    PENDING = 0
    SUCCEEDED = 1
    TIMED_OUT = 2
    CANCELLED = 3
    FAILED = 4


class AckStatus(Enum):
    """Result of OperationManager.on_ack()."""
    RESOLVED = "resolved"                      # pending operation finished by this ACK
    DUPLICATE = "duplicate"                    # operation already SUCCEEDED
    LATE_AFTER_TIMEOUT = "late_after_timeout"  # operation already TIMED_OUT
    LATE_AFTER_CANCEL = "late_after_cancel"    # operation already CANCELLED
    LATE_AFTER_FAIL = "late_after_fail"        # operation already FAILED


@dataclass(slots=True)
class OperationRecord:
    """
    Bookkeeping record of one asynchronous operation.

    Attributes:
        operation_id: Deterministic id ("op-N").
        request_id: Business request this operation carries (None for pure control ops).
        visit_id: Visit created for the destination station (None if destination is Sink).
        sender_id: LP id that created the operation (the one that waits for the ACK).
        receiver_id: LP id the ARRIVAL event is addressed to.
        created_at: Simulation time of creation.
        deadline_at: Simulation time of the OP_TIMEOUT event, or None if disabled.
        state: Current OperationState.
        accepted: Admission result carried by the ACK (None until SUCCEEDED).
        future: Future resolved exactly once (result = accepted flag; exceptions for
            TIMED_OUT / CANCELLED / FAILED). None if no future factory was supplied.
        finished_at: Simulation time at which the operation finished.
        reason: Diagnostic text for FAILED / CANCELLED.
    """
    operation_id: str
    request_id: Optional[str]
    visit_id: Optional[str]
    sender_id: int
    receiver_id: int
    created_at: float
    deadline_at: Optional[float]
    state: OperationState = OperationState.PENDING
    accepted: Optional[bool] = None
    future: Optional[asyncio.Future] = None
    finished_at: Optional[float] = None
    reason: Optional[str] = None


_OP_PREFIX = "op-"


# -------------------------------------------------------------------------
# Manager
# -------------------------------------------------------------------------
class OperationManager:
    """
    Per-replication manager of asynchronous operations (one instance per run).

    The manager is owned by one LP (the router). That LP must route the events
    EVENT_ADMISSION_ACK and EVENT_OP_TIMEOUT to on_ack() / on_timeout().

    Args:
        owner_lp_id: LP id that creates operations, waits for ACKs and receives
            OP_TIMEOUT events.
        schedule_event: Callable used to schedule an event (normally the owner LP's
            send_event; pass ``lambda e: lp.send_event(e)`` because the dispatcher
            rebinds send_event at registration time).
        future_factory: Callable creating a Future bound to the RUNNING loop
            (normally ``event_loop.create_future``). If None, no Future is created
            and wait_ack() is unavailable (useful for synchronous unit tests).
        deadline_s: ACK deadline in simulation seconds. None disables timeouts
            (baseline). When given it must be finite and > 0.
        lp_exists: Optional predicate telling whether a destination LP id is
            registered. Used to detect a missing destination at send time.
        strict_pairing: If True, an ACK must come from the operation's receiver and
            (when both are present) carry the same visit_id as the operation.
            A mismatch is a communication failure.
        retain_records: Keep finished records for inspection (tests/diagnostics).
            Off by default to bound memory in long runs.
        trace_enabled: Collect (t, kind, operation_id, detail) trace tuples.
    """

    def __init__(
        self,
        owner_lp_id: int,
        schedule_event: Callable[[Event], None],
        future_factory: Optional[Callable[[], asyncio.Future]] = None,
        deadline_s: Optional[float] = None,
        lp_exists: Optional[Callable[[int], bool]] = None,
        strict_pairing: bool = True,
        retain_records: bool = False,
        trace_enabled: bool = False,
    ):
        if deadline_s is not None:
            if not isinstance(deadline_s, (int, float)) or not math.isfinite(deadline_s) or deadline_s <= 0:
                raise ValueError(f"operation deadline must be finite and > 0, got {deadline_s!r}")

        self.owner_lp_id = owner_lp_id
        self._schedule_event = schedule_event
        self._future_factory = future_factory
        self.deadline_s = float(deadline_s) if deadline_s is not None else None
        self._lp_exists = lp_exists
        self._strict_pairing = strict_pairing

        self._pending: dict[str, OperationRecord] = {}
        self._issued = 0
        # One byte per issued operation: final OperationState (0 while pending).
        # Lets us classify duplicate / late ACKs without keeping every record.
        self._state_codes = bytearray()
        self._records: Optional[dict[str, OperationRecord]] = {} if retain_records else None

        self._failed = False
        self._failure_reason: Optional[str] = None
        self._closed = False
        self._last_t = 0.0

        self.trace_enabled = trace_enabled
        self.trace: list[tuple[float, str, Optional[str], str]] = []

        self._counters = {
            "created": 0,
            "succeeded": 0,
            "acks_accepted": 0,
            "acks_rejected": 0,
            "duplicate_acks": 0,
            "late_acks_after_timeout": 0,
            "late_acks_after_cancel": 0,
            "late_acks_after_fail": 0,
            "timeouts_scheduled": 0,
            "timeouts_processed": 0,
            "timeouts_ignored": 0,
            "timed_out": 0,
            "cancelled": 0,
            "failed": 0,
            "pending_at_close": 0,
        }

    # ------------------------------------------------------------------ props
    @property
    def pending_count(self) -> int:
        """Number of operations still waiting for an ACK."""
        return len(self._pending)

    @property
    def failed(self) -> bool:
        """True once a communication failure has been signalled."""
        return self._failed

    @property
    def failure_reason(self) -> Optional[str]:
        """Diagnostic text of the first communication failure, if any."""
        return self._failure_reason

    def is_pending(self, operation_id: str) -> bool:
        return operation_id in self._pending

    def get_record(self, operation_id: str) -> Optional[OperationRecord]:
        """Return a pending record, or a finished one if retain_records=True."""
        rec = self._pending.get(operation_id)
        if rec is not None:
            return rec
        if self._records is not None:
            return self._records.get(operation_id)
        return None

    def stats(self) -> dict[str, Any]:
        """Snapshot of counters plus failure information."""
        out: dict[str, Any] = dict(self._counters)
        out["pending"] = len(self._pending)
        out["failed_run"] = self._failed
        out["failure_reason"] = self._failure_reason
        return out

    # ----------------------------------------------------------------- create
    def create(
        self,
        t: float,
        receiver_id: int,
        request: Optional[Request] = None,
        visit: Optional[Visit] = None,
    ) -> OperationRecord:
        """
        Register a new PENDING operation at simulation time t.

        Does not block. If a deadline is configured, schedules the OP_TIMEOUT event
        (to the owner LP) at t + deadline. Does not schedule the ARRIVAL event itself;
        the caller builds it with payload_for(record, request, visit).

        Raises:
            OperationFailedError: manager already failed/closed, or the destination
                LP does not exist (the new operation is moved to FAILED first).
        """
        if self._failed:
            raise OperationFailedError(f"manager already failed: {self._failure_reason}")
        if self._closed:
            raise OperationFailedError("operation manager is closed")
        if not isinstance(t, (int, float)) or not math.isfinite(t) or t < 0:
            raise ValueError(f"invalid operation creation time {t!r}")

        self._last_t = t
        self._issued += 1
        op_id = f"{_OP_PREFIX}{self._issued}"
        self._state_codes.append(int(OperationState.PENDING))

        deadline_at = (t + self.deadline_s) if self.deadline_s is not None else None
        rec = OperationRecord(
            operation_id=op_id,
            request_id=request.request_id if request is not None else None,
            visit_id=visit.visit_id if visit is not None else None,
            sender_id=self.owner_lp_id,
            receiver_id=receiver_id,
            created_at=float(t),
            deadline_at=deadline_at,
        )
        self._pending[op_id] = rec
        self._counters["created"] += 1
        self._trace(t, "create", op_id, f"to LP {receiver_id}")

        if self._lp_exists is not None and not self._lp_exists(receiver_id):
            self.fail(f"destination LP {receiver_id} does not exist", operation_id=op_id, t=t)

        if self._future_factory is not None:
            rec.future = self._future_factory()

        if deadline_at is not None:
            self._schedule_event(Event(
                timestamp=deadline_at,
                sender_id=self.owner_lp_id,
                receiver_id=self.owner_lp_id,
                event_type=EVENT_OP_TIMEOUT,
                payload=OperationPayload(operation_id=op_id),
            ))
            self._counters["timeouts_scheduled"] += 1
            self._trace(t, "timeout_scheduled", op_id, f"at {deadline_at}")

        return rec

    @staticmethod
    def payload_for(
        record: OperationRecord,
        request: Optional[Request] = None,
        visit: Optional[Visit] = None,
    ) -> OperationPayload:
        """Build the ARRIVAL payload that carries record.operation_id to the destination."""
        return OperationPayload(operation_id=record.operation_id, request=request, visit=visit)

    async def wait_ack(self, record: OperationRecord) -> bool:
        """
        Suspend the calling coroutine until the admission ACK arrives.

        Non-blocking for the simulator: only this coroutine is suspended; the
        dispatcher keeps processing events of other LPs. Returns the admission flag
        (True = accepted, False = rejected; both are successful communication).

        Raises:
            OperationTimeoutError / OperationCancelledError / OperationFailedError.
            RuntimeError: if the manager was built without a future_factory.
        """
        if record.future is None:
            raise RuntimeError("no Future bound to this operation (future_factory not supplied)")
        return await record.future

    # -------------------------------------------------------------------- ACK
    def on_ack(self, event: Event) -> AckStatus:
        """
        Handle an ADMISSION_ACK event.

        * Pending operation: SUCCEEDED, Future resolved once with the accepted flag.
        * Already finished operation (duplicate or late ACK): counted and ignored,
          the Future is never resolved a second time.
        * Unknown operation id or malformed payload: communication failure.
        """
        t = event.timestamp
        self._last_t = t
        if event.event_type != EVENT_ADMISSION_ACK:
            self.fail(f"on_ack received event type {event.event_type!r}", t=t)
        payload = self._payload_of(event)
        op_id = payload.operation_id
        if op_id is None:
            self.fail("ACK payload without operation_id", t=t)

        rec = self._pending.get(op_id)
        if rec is None:
            return self._classify_unmatched_ack(op_id, t)

        if payload.accepted is None:
            self.fail(f"ACK for {op_id} carries no admission result", operation_id=op_id, t=t)

        if self._strict_pairing:
            if event.sender_id != rec.receiver_id:
                self.fail(
                    f"ACK for {op_id} sent by LP {event.sender_id}, expected LP {rec.receiver_id}",
                    operation_id=op_id, t=t)
            if (payload.visit is not None and rec.visit_id is not None
                    and payload.visit.visit_id != rec.visit_id):
                self.fail(
                    f"ACK for {op_id} carries visit {payload.visit.visit_id}, expected {rec.visit_id}",
                    operation_id=op_id, t=t)

        accepted = bool(payload.accepted)
        self._finish(rec, OperationState.SUCCEEDED, t, accepted=accepted)
        self._counters["acks_accepted" if accepted else "acks_rejected"] += 1
        return AckStatus.RESOLVED

    def _classify_unmatched_ack(self, op_id: str, t: float) -> AckStatus:
        idx = self._index_of(op_id)
        if idx is None:
            self.fail(f"ACK for unknown operation id {op_id!r}", t=t)
        state = OperationState(self._state_codes[idx - 1])
        if state is OperationState.SUCCEEDED:
            self._counters["duplicate_acks"] += 1
            status = AckStatus.DUPLICATE
        elif state is OperationState.TIMED_OUT:
            self._counters["late_acks_after_timeout"] += 1
            status = AckStatus.LATE_AFTER_TIMEOUT
        elif state is OperationState.CANCELLED:
            self._counters["late_acks_after_cancel"] += 1
            status = AckStatus.LATE_AFTER_CANCEL
        else:
            self._counters["late_acks_after_fail"] += 1
            status = AckStatus.LATE_AFTER_FAIL
        self._trace(t, "ack_ignored", op_id, status.value)
        return status

    # ---------------------------------------------------------------- timeout
    def on_timeout(self, event: Event) -> bool:
        """
        Handle an OP_TIMEOUT event (simulation time).

        Returns True if this event ended a still-pending operation (TIMED_OUT),
        False if the operation had already finished (event ignored).
        The business request is not touched in any way.
        """
        t = event.timestamp
        self._last_t = t
        if event.event_type != EVENT_OP_TIMEOUT:
            self.fail(f"on_timeout received event type {event.event_type!r}", t=t)
        payload = self._payload_of(event)
        op_id = payload.operation_id
        if op_id is None:
            self.fail("timeout payload without operation_id", t=t)

        rec = self._pending.get(op_id)
        if rec is None:
            if self._index_of(op_id) is None:
                self.fail(f"timeout for unknown operation id {op_id!r}", t=t)
            self._counters["timeouts_ignored"] += 1
            self._trace(t, "timeout_ignored", op_id, "already finished")
            return False

        self._counters["timeouts_processed"] += 1
        self._finish(rec, OperationState.TIMED_OUT, t, reason=f"ACK deadline {self.deadline_s}s expired")
        return True

    # ----------------------------------------------------------------- cancel
    def cancel(self, operation_id: str, t: Optional[float] = None, reason: str = "cancelled") -> bool:
        """
        Cancel a PENDING operation (waiting only; the request is unaffected).

        Returns True if the operation was pending and is now CANCELLED, False if it
        had already finished or is unknown.
        """
        t = self._last_t if t is None else t
        self._last_t = t
        rec = self._pending.get(operation_id)
        if rec is None:
            return False
        self._finish(rec, OperationState.CANCELLED, t, reason=reason)
        return True

    # ------------------------------------------------------------------- fail
    def fail(self, reason: str, operation_id: Optional[str] = None, t: Optional[float] = None) -> NoReturn:
        """
        Signal a communication failure and abort the replication in a controlled way.

        * the named operation (if pending) becomes FAILED;
        * every other pending operation is also moved to FAILED and removed, so no
          coroutine stays suspended on a Future that will never be resolved;
        * the first reason is stored for diagnostics;
        * OperationFailedError is raised; propagating out of handle_event it makes
          BkSysCoEventLoop stop with status FAILED and failure_reason set.

        A failure is never counted as a DROPPED request.
        """
        t = self._last_t if t is None else t
        if self._failure_reason is None:
            self._failure_reason = reason
        self._failed = True
        rec = self._pending.get(operation_id) if operation_id is not None else None
        if rec is not None:
            self._finish(rec, OperationState.FAILED, t, reason=reason)
        self._abort_pending(OperationState.FAILED, t, reason)
        self._trace(t, "failed", operation_id, reason)
        raise OperationFailedError(reason)

    # ------------------------------------------------------------------ close
    def close(self, t: Optional[float] = None, reason: str = "simulation_end") -> int:
        """
        Release every still-pending operation (end of replication / cleanup).

        Pending operations become CANCELLED (waiters get OperationCancelledError) and
        no new operation can be created. This only cleans waiting registrations; it
        does not change any request outcome. Also safe to call after a loop failure
        (e.g. a failure raised by the loop itself rather than by this manager).

        Returns:
            Number of operations that were still pending.
        """
        t = self._last_t if t is None else t
        n = self._abort_pending(OperationState.CANCELLED, t, reason)
        self._counters["pending_at_close"] += n
        self._closed = True
        return n

    # ---------------------------------------------------------------- helpers
    def _abort_pending(self, state: OperationState, t: float, reason: str) -> int:
        recs = list(self._pending.values())
        for rec in recs:
            self._finish(rec, state, t, reason=reason)
        return len(recs)

    def _finish(
        self,
        rec: OperationRecord,
        state: OperationState,
        t: float,
        accepted: Optional[bool] = None,
        reason: Optional[str] = None,
    ) -> None:
        """Single exit point of the lifecycle: PENDING -> final state, exactly once."""
        if rec.state is not OperationState.PENDING:
            return  # already finished; never resolve a Future twice
        rec.state = state
        rec.finished_at = t
        rec.accepted = accepted
        rec.reason = reason
        self._pending.pop(rec.operation_id, None)
        idx = self._index_of(rec.operation_id)
        if idx is not None:
            self._state_codes[idx - 1] = int(state)
        if self._records is not None:
            self._records[rec.operation_id] = rec

        key = {
            OperationState.SUCCEEDED: "succeeded",
            OperationState.TIMED_OUT: "timed_out",
            OperationState.CANCELLED: "cancelled",
            OperationState.FAILED: "failed",
        }[state]
        self._counters[key] += 1
        self._resolve_future(rec, state, accepted, reason)
        self._trace(t, state.name.lower(), rec.operation_id,
                    f"accepted={accepted}" if state is OperationState.SUCCEEDED else (reason or ""))

    @staticmethod
    def _resolve_future(rec: OperationRecord, state: OperationState,
                        accepted: Optional[bool], reason: Optional[str]) -> None:
        fut = rec.future
        if fut is None or fut.done():
            return
        try:
            if state is OperationState.SUCCEEDED:
                fut.set_result(bool(accepted))
                return
            if state is OperationState.TIMED_OUT:
                exc: Exception = OperationTimeoutError(reason or "operation timed out")
            elif state is OperationState.CANCELLED:
                exc = OperationCancelledError(reason or "operation cancelled")
            else:
                exc = OperationFailedError(reason or "operation failed")
            fut.set_exception(exc)
            # Mark the exception as retrieved so asyncio does not log "Future exception
            # was never retrieved" when nobody is awaiting this operation. Waiters that
            # await it later still receive the exception.
            fut.exception()
        except RuntimeError:
            # The asyncio loop that owns the Future is already closed (cleanup after
            # Simulation.run()). Nobody can be waiting any more; the operation state
            # itself has already been updated, so there is nothing else to do.
            pass

    @staticmethod
    def _index_of(operation_id: Optional[str]) -> Optional[int]:
        """Parse 'op-N' into N; None if the id is not a valid, already issued id."""
        if not isinstance(operation_id, str) or not operation_id.startswith(_OP_PREFIX):
            return None
        digits = operation_id[len(_OP_PREFIX):]
        if not digits.isdigit():
            return None
        n = int(digits)
        return n if n >= 1 else None

    def _payload_of(self, event: Event) -> OperationPayload:
        """Normalise event.payload to OperationPayload; malformed payload is a failure."""
        p = event.payload
        if isinstance(p, OperationPayload):
            payload = p
        elif isinstance(p, dict):
            payload = OperationPayload(
                operation_id=p.get("operation_id"),
                request=p.get("request"),
                visit=p.get("visit"),
                accepted=p.get("accepted"),
                details=p.get("details"),
            )
        else:
            self.fail(f"malformed payload type {type(p).__name__} in {event.event_type}",
                      t=event.timestamp)
        # An id that was never issued (checked only for ids we are about to look up)
        idx = self._index_of(payload.operation_id) if payload.operation_id is not None else None
        if payload.operation_id is not None and (idx is None or idx > self._issued):
            self.fail(f"unknown operation id {payload.operation_id!r}", t=event.timestamp)
        return payload

    def _trace(self, t: float, kind: str, operation_id: Optional[str], detail: str) -> None:
        if self.trace_enabled:
            self.trace.append((t, kind, operation_id, detail))
